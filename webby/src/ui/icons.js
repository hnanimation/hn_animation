/**
 * يُعيد أيقونة بحجم مخصص
 */
export function getIcon(name, size = SIZE_DEFAULT) {
  const template = ICONS[name];
  if (!template) {
    console.warn('[Webby] unknown icon:', name);
    return '';
  }
  return template.replace(/width="24" height="24"/, `width="${size}" height="${size}"`);
}

/**
 * يملأ كل عناصر [data-icon] في DOM
 */
export function fillIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    const name = el.getAttribute('data-icon');
    const size = parseInt(el.getAttribute('data-icon-size') || '24', 10);
    el.innerHTML = getIcon(name, size);
  });
}